"""Re-establish the abstention verdicts in a committed run file.

Every run in ``eval/results/`` was graded by a judge whose output was truncated
to five tokens, which recorded every refusal as an answer. The answers
themselves are fine -- they were generated by the pipeline and stored verbatim
-- so the abstention numbers can be rebuilt from the files without re-running
the pipeline, re-generating a single answer, or spending generation quota.

That is the whole reason this exists as a command rather than a note saying the
old numbers were wrong: a result that cannot be recomputed is an anecdote.

What it does **not** do is re-run RAGAS. Faithfulness and the rest are unchanged
by a re-judgement, except that a question newly recognised as a refusal should
not carry a faithfulness score at all. Those scores are dropped rather than
recomputed, and the count of graded samples is corrected, so an aggregate is
never quietly averaged over a different set of questions than it claims.
"""

from __future__ import annotations

import asyncio
from collections.abc import Callable
from pathlib import Path

from vidyarag.evaluation.abstention import (
    AbstentionStats,
    JudgeVerdict,
    is_structural_abstention,
    judge_abstention,
    summarise_abstention,
)
from vidyarag.evaluation.answer_cache import AnswerCache, abstention_key
from vidyarag.evaluation.goldset import GoldQuestion
from vidyarag.evaluation.metrics import RateLimiter
from vidyarag.evaluation.runner import ABSTENTION_CACHE_DIR, EvalRun, load_run


async def rejudge_run(
    run: EvalRun,
    *,
    client: object,
    judge_model: str,
    goldset: list[GoldQuestion],
    rate: float = 6.0,
    use_cache: bool = True,
    on_verdict: Callable[[str, JudgeVerdict], None] | None = None,
) -> EvalRun:
    """Re-judge every answer in ``run`` and rebuild its abstention block.

    Args:
        run: A loaded evaluation run. Modified in place and returned.
        client: An OpenAI-compatible async client pointed at the judge model.
        judge_model: The judging model id.
        goldset: The gold questions, for answerability.
        rate: Judgements per minute, paced against the free tier.
        use_cache: Reuse verdicts from disk. The cache key carries a judge
            version, so verdicts from the broken judge are never reused.
        on_verdict: Progress callback.

    Returns:
        The same run, with per-sample provenance and a corrected aggregate.
    """
    questions = {q.id: q for q in goldset}
    verdicts = AnswerCache(ABSTENTION_CACHE_DIR if use_cache else None)
    limiter = RateLimiter(rate)

    for sample in run.samples:
        if sample.error is not None or not sample.answer:
            continue

        # Structural abstentions are exact and free: the pipeline emitted its
        # own sentinel, or the corrective loop set the flag. Nothing to judge.
        if is_structural_abstention(
            sample.answer, trace_abstained=bool(sample.corrective.get("abstained"))
        ):
            sample.abstained = True
            sample.abstention_judge = {"source": "structural", "measured": True}
            if on_verdict is not None:
                on_verdict(sample.id, JudgeVerdict(refused=True, measured=True, raw="structural"))
            continue

        key = abstention_key(
            judge_model=judge_model, question=sample.question, answer=sample.answer
        )
        entry = verdicts.get(key)
        if entry is not None:
            verdict = JudgeVerdict(
                refused=bool(entry["abstained"]),
                measured=bool(entry.get("measured", True)),
                raw=str(entry.get("raw", "")),
                error=str(entry.get("error", "")),
            )
        else:
            await limiter.acquire()
            loop = asyncio.get_running_loop()
            started = loop.time()
            verdict = await judge_abstention(
                client,
                model=judge_model,
                question=sample.question,
                answer=sample.answer,
            )
            limiter.observe(loop.time() - started)
            # Only a real verdict is cached. A failure is not a judgement, and
            # caching one turns a transient 429 into a permanent hole in the
            # metric: the next run reads the failure back off disk, never
            # retries it, and reports a number computed over fewer questions
            # than it claims -- which is the failure this whole module exists
            # to correct, reintroduced one layer down.
            if verdict.measured:
                verdicts.put(
                    key,
                    {
                        "abstained": verdict.refused,
                        "measured": True,
                        "raw": verdict.raw,
                    },
                )

        sample.abstained = verdict.refused
        sample.abstention_judge = {
            "source": "judge",
            "model": judge_model,
            "measured": verdict.measured,
            "raw": verdict.raw,
            "error": verdict.error,
        }
        # A refusal has no faithfulness to measure. Keeping a score computed
        # when the question was thought to be answered would average a refusal
        # into a metric that excludes refusals everywhere else.
        if verdict.refused and sample.ragas:
            sample.ragas = {}
            sample.ragas_errors = {"abstention": "dropped: re-judged as a refusal"}
        if on_verdict is not None:
            on_verdict(sample.id, verdict)

    _rebuild_aggregates(run, questions)
    return run


def _rebuild_aggregates(run: EvalRun, questions: dict[str, GoldQuestion]) -> None:
    """Recompute the abstention block and the RAGAS means over what remains."""
    judged = [s for s in run.samples if s.id in questions and s.error is None]
    stats: AbstentionStats = summarise_abstention(
        [(questions[s.id].is_answerable, s.abstained) for s in judged],
        unmeasured=sum(
            1 for s in judged if s.abstention_judge and not s.abstention_judge.get("measured")
        ),
    )
    run.abstention = stats.as_dict()

    scored = [s for s in run.samples if s.ragas]
    for metric in ("faithfulness", "answer_relevancy", "context_precision", "context_recall"):
        values = [value for s in scored if (value := s.ragas.get(metric)) is not None]
        run.aggregates[metric] = sum(values) / len(values) if values else None
    run.aggregates["graded_samples"] = float(len(scored))


def load_runs(paths: list[Path]) -> list[EvalRun]:
    """Load run files in the order given."""
    return [load_run(path) for path in paths]
